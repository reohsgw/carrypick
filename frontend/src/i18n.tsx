export type Lang = 'ko' | 'en';
const DICTS: Record<Lang, Record<Key, string>> = { ko, en };
const LANG_KEY = 'carrypick.lang';

function savedLang(): Lang {
  try {
    const v = localStorage.getItem(LANG_KEY);
    return v === 'en' || v === 'ko' ? v : 'ko';
  } catch {
    return 'ko';
  }
}

export type Vars = Record<string, string | number | null | undefined>;
export type T = (key: Key, vars?: Vars) => string;

interface I18n { lang: Lang; setLang: (l: Lang) => void; t: T }
const Ctx = createContext<I18n | null>(null);

export function fill(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? '' : String(vars[k])));
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(savedLang);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try { localStorage.setItem(LANG_KEY, l); } catch { /* keep for this tab only */ }
    document.documentElement.lang = l;
  }, []);
  const value = useMemo<I18n>(() => {
    document.documentElement.lang = lang;
    return { lang, setLang, t: (key, vars) => fill(DICTS[lang][key] ?? en[key] ?? String(key).split(".").pop(), vars) };
  }, [lang, setLang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error('useI18n must be used inside I18nProvider');
  return v;
}

/** Small segmented KO / EN switch. */
export function LangToggle({ dark }: { dark?: boolean }) {
  const { lang, setLang, t } = useI18n();
  return (
    <div className={`lang ${dark ? 'is-dark' : ''}`} role="group" aria-label={t('lang.label')}>
      {(['ko', 'en'] as const).map((l) => (
        <button key={l} type="button" aria-pressed={lang === l} onClick={() => setLang(l)}>
          {l === 'ko' ? '한국어' : 'EN'}
        </button>
      ))}
    </div>
  );
}

/** Error to a sentence in the current language: known server codes are translated, others keep the server text. */
export function useErrorText() {
  const { t } = useI18n();
  return useCallback(
    (err: unknown): string => {
      const info = errorInfo(err);
      if (info.network) return t('err.network');
      const key = `err.${info.code}` as Key;
      if (info.code && key in en) return t(key);
      return info.message ?? t('err.generic');
    },
    [t],
  );
}
